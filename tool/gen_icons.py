#!/usr/bin/env python3
"""Regenerates lib/core/theme/icons.dart from the Ph/PhFill/PhBold names used in lib/.

Code points come from phosphor_flutter 2.1.0 in the pub cache (fonts are bundled
in assets/fonts). Run after using a new icon:  python3 tool/gen_icons.py
"""
import glob, os, re, sys

pub = os.environ.get('PUB_CACHE', os.path.expanduser('~/.pub-cache'))
src = os.path.join(pub, 'hosted/pub.dev/phosphor_flutter-2.1.0/lib/src/')
if not os.path.isdir(src):
    sys.exit('Run `dart pub cache add phosphor_flutter --version 2.1.0` first.')
styles = {
    'Ph': ('PhosphorRegular', 'phosphor_icons_regular.dart'),
    'PhFill': ('PhosphorFill', 'phosphor_icons_fill.dart'),
    'PhBold': ('PhosphorBold', 'phosphor_icons_bold.dart'),
}
code = ''.join(open(f).read() for f in glob.glob('lib/**/*.dart', recursive=True) if not f.endswith('icons.dart'))
out = [
    '// Phosphor icons (MIT, phosphoricons.com) as const IconData.',
    '//',
    '// phosphor_flutter 2.1.0 subclasses IconData, which Flutter 3.50 made final,',
    '// so the fonts are bundled directly (assets/fonts/Phosphor-*.ttf) and only the',
    '// icons the app uses are declared here. Const IconData keeps icon',
    '// tree-shaking working in release builds.',
    '// GENERATED by tool/gen_icons.py. Do not edit by hand.',
    'library;',
    '',
    "import 'package:flutter/widgets.dart';",
    '',
]
for cls, (family, file) in styles.items():
    names = sorted(set(re.findall(r'\b' + cls + r'\.(\w+)', code)))
    table = open(src + file).read()
    out.append(f'abstract final class {cls} {{')
    for n in names:
        m = re.search(r'static const ' + n + r' = Phosphor\w*IconData\((0x[0-9a-f]+)', table)
        if not m:
            sys.exit(f'Unknown icon {cls}.{n}')
        out.append(f"  static const {n} = IconData({m.group(1)}, fontFamily: '{family}', matchTextDirection: true);")
    out += ['}', '']
open('lib/core/theme/icons.dart', 'w').write('\n'.join(out))
print('icons:', {c: len(set(re.findall(r'\b' + c + r'\.(\w+)', code))) for c in styles})
